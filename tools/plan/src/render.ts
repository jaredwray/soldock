import { isSettled, type Plan, type Stage, type Task } from "./model.ts";
import { readyTasks, stagesAwaitingExit, stagesAwaitingKickoff, tasksWithStatus } from "./schedule.ts";

function progress(stage: Stage): { settled: number; total: number } {
	const live = stage.tasks.filter((t) => t.status !== "dropped");
	return { settled: live.filter((t) => isSettled(t.status)).length, total: live.length };
}

function bar(settled: number, total: number, width = 10): string {
	const filled = total === 0 ? 0 : Math.round((settled / total) * width);
	return `${"█".repeat(filled)}${"░".repeat(width - filled)}`;
}

function stageLink(stage: Stage): string {
	const base = stage.file.split("/").pop() ?? stage.file;
	return `[${stage.id}](stages/${base})`;
}

function taskLine(plan: Plan, task: Task): string {
	const stage = plan.stages.find((s) => s.id === task.stageId);
	const link = stage ? `stages/${stage.file.split("/").pop()}` : "";
	const suffix = task.reason ? ` — ${task.reason}` : "";
	return `- [${task.id}](${link}) · ${task.title} _(${task.kind}, ${task.size})_${suffix}`;
}

/** Renders plan/STATUS.md. Output is deterministic so CI can diff it. */
export function renderStatus(plan: Plan): string {
	const all = plan.stages.flatMap((s) => s.tasks).filter((t) => t.status !== "dropped");
	const done = all.filter((t) => t.status === "done").length;
	const pct = all.length === 0 ? 0 : Math.round((done / all.length) * 100);
	const active = plan.stages.filter((s) => s.status === "active").map((s) => s.id);

	const out: string[] = [];
	out.push("<!-- GENERATED by `pnpm plan status --write` from plan/stages/*.md. Do not edit by hand. -->");
	out.push("");
	out.push("# Build status");
	out.push("");
	out.push(
		`**${done} / ${all.length} tasks done (${pct}%)** · active stage(s): ${active.length > 0 ? active.join(", ") : "none"}`,
	);
	out.push("");
	out.push("The stage files in [`stages/`](stages/) are the source of truth; this page is regenerated from them.");
	out.push("Run `pnpm plan next` to see what to work on and [`process.md`](process.md) for how.");
	out.push("");
	out.push("| Stage | Title | Status | Progress | Depends on |");
	out.push("| --- | --- | --- | --- | --- |");
	for (const stage of plan.stages) {
		const { settled, total } = progress(stage);
		out.push(
			`| ${stageLink(stage)} | ${stage.title} | ${stage.status} | \`${bar(settled, total)}\` ${settled}/${total} | ${stage.depends.join(", ") || "—"} |`,
		);
	}

	const gates = [
		...stagesAwaitingExit(plan).map(
			(s) => `- ${stageLink(s)} · ${s.title}: every task is settled; run the **exit gate**`,
		),
		...stagesAwaitingKickoff(plan).map(
			(s) => `- ${stageLink(s)} · ${s.title}: dependencies done; run the **kickoff gate**`,
		),
	];
	out.push("");
	out.push("## Gates due");
	out.push("");
	out.push(gates.length > 0 ? gates.join("\n") : "_None._");

	const sections: Array<[string, Task[]]> = [
		["In progress", tasksWithStatus(plan, "in-progress")],
		["Blocked", tasksWithStatus(plan, "blocked")],
		["Ready to start", readyTasks(plan)],
	];
	for (const [heading, tasks] of sections) {
		out.push("");
		out.push(`## ${heading}`);
		out.push("");
		if (tasks.length === 0) {
			out.push("_None._");
		} else {
			for (const task of tasks) out.push(taskLine(plan, task));
		}
	}

	out.push("");
	out.push("## Stage map");
	out.push("");
	out.push("```mermaid");
	out.push("graph LR");
	for (const stage of plan.stages) {
		const { settled, total } = progress(stage);
		out.push(
			`  ${stage.id}["${stage.id} ${stage.title.replace(/"/g, "'")}<br/>${settled}/${total}"]:::${stage.status}`,
		);
	}
	for (const stage of plan.stages) {
		for (const dep of stage.depends) out.push(`  ${dep} --> ${stage.id}`);
	}
	out.push("  classDef planned fill:#f4f4f5,stroke:#a1a1aa,color:#18181b");
	out.push("  classDef active fill:#dbeafe,stroke:#2563eb,color:#1e3a8a");
	out.push("  classDef done fill:#dcfce7,stroke:#16a34a,color:#14532d");
	out.push("```");
	out.push("");
	return out.join("\n");
}
